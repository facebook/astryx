/**
 * @file scripts/swift-ios-theme.mjs
 * @input Core's theme resolver, run over the default theme in light and dark
 * @output apple/Sources/Astryx/Theme/Generated/DefaultTheme.swift
 * @position Run by `generate:swift-ios`; the Swift output is committed and a
 *   test fails when it drifts from core's tokens
 */

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const PACKAGE_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
export const SWIFT_IOS_THEME_FILE = path.join(
  PACKAGE_ROOT,
  'apple',
  'Sources',
  'Astryx',
  'Theme',
  'Generated',
  'DefaultTheme.swift',
);

// The token groups the Swift components read. Everything else (shadows,
// motion, layout breakpoints) stays out until a component needs it.
const KEEP =
  /^--(color-|spacing-|radius-|size-element-|border-width$|font-family-|font-size-|font-weight-|text-(heading-\d|body|large|label|supporting)-)/;
const REM = 16;

function hex2(n) {
  return Math.round(n).toString(16).padStart(2, '0').toUpperCase();
}

// The CSS color keywords core's resolved tokens use.
const NAMED_COLORS = {
  black: '#000000FF',
  white: '#FFFFFFFF',
  transparent: '#00000000',
};

/** A CSS color as `#RRGGBBAA`, or null when it is not a plain color. */
export function toHexColor(value) {
  const v = value.trim();
  let m = /^#([0-9a-f]{3,8})$/i.exec(v);
  if (m) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = [...h].map(c => c + c).join('');
    if (h.length === 6) h += 'FF';
    return h.length === 8 ? `#${h.toUpperCase()}` : null;
  }
  m =
    /^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:[,\s/]+([\d.]+%?))?\s*\)$/i.exec(
      v,
    );
  if (m) {
    const alpha =
      m[4] === undefined
        ? 1
        : m[4].endsWith('%')
          ? parseFloat(m[4]) / 100
          : parseFloat(m[4]);
    return `#${hex2(+m[1])}${hex2(+m[2])}${hex2(+m[3])}${hex2(alpha * 255)}`;
  }
  return NAMED_COLORS[v.toLowerCase()] ?? null;
}

/** A CSS font-family stack as its family names, first choice first. */
export function toFontFamilies(value) {
  return value
    .split(',')
    .map(family => family.trim().replace(/^(["'])(.*)\1$/, '$2'))
    .filter(Boolean);
}

/** A CSS length or unitless number as points, or null. */
export function toPoints(value) {
  const m = /^(-?[\d.]+)(rem|px)?$/.exec(value.trim());
  if (!m) return null;
  return m[2] === 'rem' ? parseFloat(m[1]) * REM : parseFloat(m[1]);
}

async function resolveMode(mode) {
  const {defineTheme} = await import('@astryxdesign/core/theme');
  const {resolveThemeTokens} = await import('@astryxdesign/core/theme/tokens');
  const theme = defineTheme({name: 'astryx', tokens: {}});
  const colors = {};
  const sizes = {};
  const fonts = {};
  for (const [name, value] of Object.entries(
    resolveThemeTokens(theme, {mode}),
  )) {
    if (!KEEP.test(name) || typeof value !== 'string') continue;
    const key = name.slice(2);
    // A kept token that cannot be read fails the run, so no token goes
    // missing from the Swift theme without a message.
    if (key.startsWith('font-family-')) {
      const families = toFontFamilies(value);
      if (families.length === 0) {
        throw new Error(`${mode}: ${name} names no font family: ${value}`);
      }
      fonts[key] = families;
    } else if (key.startsWith('color-')) {
      const color = toHexColor(value);
      if (color === null) {
        throw new Error(
          `${mode}: ${name} is not a color Swift can read: ${value}`,
        );
      }
      colors[key] = color;
    } else {
      const points = toPoints(value);
      if (points === null) {
        throw new Error(
          `${mode}: ${name} is not a size Swift can read: ${value}`,
        );
      }
      sizes[key] = points;
    }
  }
  return {colors, sizes, fonts};
}

function swiftDictionary(entries, format) {
  const keys = Object.keys(entries).sort();
  return keys.map(key => `      "${key}": ${format(entries[key])},`).join('\n');
}

function swiftTokens(name, mode, {colors, sizes, fonts}) {
  return `  /// Core's default theme, ${mode} mode.
  public static let ${name} = AstryxTokens(
    colors: [
${swiftDictionary(colors, v => `"${v}"`)}
    ],
    sizes: [
${swiftDictionary(sizes, v => String(v))}
    ],
    fonts: [
${swiftDictionary(fonts, v => `[${v.map(f => JSON.stringify(f)).join(', ')}]`)}
    ]
  )`;
}

/** The generated Swift source for core's default theme. */
export async function renderSwiftIOSTheme() {
  const light = await resolveMode('light');
  const dark = await resolveMode('dark');
  return `// Generated by @astryxdesign/native from core's theme resolver. Do not edit.
// Run \`pnpm -F @astryxdesign/native generate:swift-ios\` after a core token change.

extension AstryxTokens {
${swiftTokens('defaultLight', 'light', light)}

${swiftTokens('defaultDark', 'dark', dark)}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.dirname(SWIFT_IOS_THEME_FILE), {recursive: true});
  fs.writeFileSync(SWIFT_IOS_THEME_FILE, await renderSwiftIOSTheme());
  console.log(`wrote ${path.relative(PACKAGE_ROOT, SWIFT_IOS_THEME_FILE)}`);
}
