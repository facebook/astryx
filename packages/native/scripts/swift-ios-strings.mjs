/**
 * @file scripts/swift-ios-strings.mjs
 * @input Core's locale catalogs (`@astryxdesign/core/locales/*.json`)
 * @output swift-ios-1/core/Resources/<locale>.lproj/Localizable.strings
 * @position Run by `generate:swift-ios`; the output is committed and a test
 *   fails when it drifts from core's catalogs
 */

import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const PACKAGE_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
export const SWIFT_IOS_STRINGS_DIR = path.join(
  PACKAGE_ROOT,
  'swift-ios-1',
  'core',
  'Resources',
);

/** The catalog messages the Swift components speak. */
export const SWIFT_IOS_STRING_KEYS = ['@astryx.button.loading'];

// Apple's localization names where they differ from core's catalog names.
const APPLE_LOCALES = {'zh-CN': 'zh-Hans', 'zh-TW': 'zh-Hant', 'no-NO': 'nb'};

function localesDir() {
  const require = createRequire(import.meta.url);
  // Read through core's public `./locales/*.json` export.
  return path.dirname(require.resolve('@astryxdesign/core/locales/en.json'));
}

function quote(text) {
  return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
}

/**
 * The generated `.strings` files, keyed by their path under
 * `core/Resources/`. Core's pseudo-locale is left out.
 */
export function renderSwiftIOSStrings() {
  const dir = localesDir();
  const files = {};
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith('.json') || file === 'pseudo.json') continue;
    const locale = file.slice(0, -'.json'.length);
    const catalog = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    const lines = [
      "/* Generated by @astryxdesign/native from core's locale catalogs. Do not edit. */",
    ];
    for (const key of SWIFT_IOS_STRING_KEYS) {
      const entry = catalog[key];
      if (!entry) throw new Error(`${file} has no ${key}`);
      lines.push('', `/* ${entry.description.replace(/\*\//g, '* /')} */`);
      lines.push(`${quote(key)} = ${quote(entry.defaultMessage)};`);
    }
    const name = APPLE_LOCALES[locale] ?? locale;
    files[`${name}.lproj/Localizable.strings`] = `${lines.join('\n')}\n`;
  }
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.rmSync(SWIFT_IOS_STRINGS_DIR, {recursive: true, force: true});
  const files = renderSwiftIOSStrings();
  for (const [relative, text] of Object.entries(files)) {
    const out = path.join(SWIFT_IOS_STRINGS_DIR, relative);
    fs.mkdirSync(path.dirname(out), {recursive: true});
    fs.writeFileSync(out, text);
  }
  console.log(
    `wrote ${Object.keys(files).length} files to ${path.relative(PACKAGE_ROOT, SWIFT_IOS_STRINGS_DIR)}`,
  );
}
