/**
 * @file contract/generateTypeScript.ts
 * @input Component contracts
 * @output Declaration files: core.d.ts, one per native platform, and shared.d.ts
 * @position Produces the platform-scoped types (AST-082 FR5, FR6). The package
 *   exports map selects one file per type-resolution condition
 */

import {NATIVE_PLATFORMS, type NativePlatform} from '../platforms.js';
import type {ComponentContract, PropMap, PropType} from './types.js';

const HEADER = '// Generated by @astryxdesign/native. Do not edit.\n';

function tsType(type: PropType): string {
  switch (type.kind) {
    case 'string':
    case 'number':
    case 'boolean':
      return type.kind;
    case 'enum':
      return type.values.map(value => `'${value}'`).join(' | ');
    case 'numberEnum':
      return type.values.join(' | ');
    case 'array': {
      const inner = tsType(type.of);
      return `ReadonlyArray<${inner}>`;
    }
    case 'record':
      return `{${members(type.fields, ' ')}}`;
    case 'fn':
      return `(${type.args.map((arg, i) => `arg${i}: ${tsType(arg)}`).join(', ')}) => void`;
    case 'named':
      return type.name;
  }
}

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`;
}

function members(props: PropMap, separator = '\n  '): string {
  return Object.entries(props)
    .map(
      ([name, spec]) =>
        `${key(name)}${spec.optional ? '?' : ''}: ${tsType(spec.type)};`,
    )
    .join(separator);
}

function coreFile(contracts: readonly ComponentContract[]): string {
  const types = new Map<string, PropMap>();
  for (const contract of contracts) {
    for (const [name, fields] of Object.entries(contract.types)) {
      types.set(name, fields);
    }
  }
  const typeDecls = [...types].map(
    ([name, fields]) => `export interface ${name} {\n  ${members(fields)}\n}`,
  );
  const props = contracts.map(
    contract =>
      `/** Core contract. Base props attach to the ${contract.baseTarget}. */\n` +
      `export interface ${contract.name}CoreProps extends AstryxSharedBaseProps {\n  ${members(contract.core)}\n}`,
  );
  return (
    HEADER +
    '/** Base props shared by every platform (AST-082 FR7). */\n' +
    'export interface AstryxSharedBaseProps {\n  id?: string;\n  isHidden?: boolean;\n}\n' +
    [...typeDecls, ...props].join('\n') +
    '\n'
  );
}

function reExports(contracts: readonly ComponentContract[]): string {
  const names = new Set<string>(['AstryxSharedBaseProps']);
  for (const contract of contracts) {
    Object.keys(contract.types).forEach(name => names.add(name));
    names.add(`${contract.name}CoreProps`);
  }
  return `export type {${[...names].join(', ')}} from './core.js';\n`;
}

function platformFile(
  contracts: readonly ComponentContract[],
  platform: NativePlatform | null,
): string {
  const imports = `import type {${contracts.map(c => `${c.name}CoreProps`).join(', ')}} from './core.js';\n`;
  const components = contracts.map(contract => {
    const extra = platform ? (contract.platforms[platform] ?? {}) : {};
    const body = Object.keys(extra).length > 0 ? `\n  ${members(extra)}\n` : '';
    const scope = platform
      ? `core contract plus the ${platform} contract`
      : 'core contract only';
    return (
      `/** ${contract.name} props: ${scope}. */\n` +
      `export interface ${contract.name}Props extends ${contract.name}CoreProps {${body}}\n` +
      `export declare function ${contract.name}(props: ${contract.name}Props): unknown;`
    );
  });
  return HEADER + imports + reExports(contracts) + components.join('\n') + '\n';
}

/** Returns file name to contents, relative to the types output folder. */
export function generateTypeScript(
  contracts: readonly ComponentContract[],
): Record<string, string> {
  const files: Record<string, string> = {
    'core.d.ts': coreFile(contracts),
    'shared.d.ts': platformFile(contracts, null),
  };
  for (const platform of NATIVE_PLATFORMS) {
    files[`${platform}.d.ts`] = platformFile(contracts, platform);
  }
  return files;
}
