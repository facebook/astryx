/**
 * @file Generate the public `./api` type surface from the JSDoc source of truth.
 *
 * Functions own their types: each api leaf's `@returns` + colocated
 * `.type.mjs` typedefs ARE the contract. This script runs `tsc`
 * (allowJs + checkJs + declaration + emitDeclarationOnly) over the api sources
 * into a throwaway temp dir, then copies just the emitted api declaration tree
 * (the `.d.mts` files) back alongside the sources (so their relative imports and
 * shared `types` declarations resolve). `api/index.d.mts` is the entry that
 * `package.json` exports["./api"].types points at.
 *
 * The emitted `api/**\/*.d.mts` are NOT committed (they're gitignored, like the
 * other packages' `dist/`). This script runs automatically at `prepack`, so
 * `pnpm pack`/`pnpm publish` always ships a freshly generated, in-sync surface.
 * Run `pnpm sync:api-types` to produce them locally; the published surface is
 * verified end-to-end by `.github/scripts/cli-api-types-verify.mjs`.
 *
 * @position packages/cli/scripts — build tooling; not shipped runtime
 */

import {execFileSync} from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import {fileURLToPath} from 'node:url';

const CLI_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TMP = '/tmp/astryx-dts-build';
const EMITTED_API = path.join(TMP, 'packages', 'cli', 'api');
const DEST_API = path.join(CLI_ROOT, 'api');

/**
 * Banner prepended to every emitted declaration so it's obvious the file is
 * generated and must not be hand-edited — edit the `.mjs` JSDoc and re-run
 * `pnpm sync:api-types` instead. The `@generated` tag is the standard marker
 * tooling and reviewers recognize.
 */
const BANNER =
  '// @generated by scripts/sync-api-types.mjs from the JSDoc in api/**/*.mjs.\n' +
  '// DO NOT EDIT — run `pnpm sync:api-types` to regenerate.\n\n';

/**
 * Recursively copy every emitted declaration from `src` to `dest`, preserving
 * structure and prepending the generated banner.
 * @param {string} src
 * @param {string} dest
 */
function copyDts(src, dest) {
  for (const entry of fs.readdirSync(src, {withFileTypes: true})) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDts(s, d);
    } else if (entry.name.endsWith('.d.mts')) {
      fs.mkdirSync(dest, {recursive: true});
      fs.writeFileSync(d, BANNER + fs.readFileSync(s, 'utf8'));
    }
  }
}

/**
 * Recursively delete every `.d.mts` under `dir` so a regen builds from pure
 * `.mjs` source. Committed declarations sit next to their `.mjs`, and tsc would
 * otherwise resolve an import to the stale `.d.mts` instead of re-inferring from
 * the (possibly edited) source — making generation non-idempotent.
 * @param {string} dir
 */
function cleanDts(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) cleanDts(p);
    else if (entry.name.endsWith('.d.mts')) fs.rmSync(p);
  }
}

fs.rmSync(TMP, {recursive: true, force: true});
cleanDts(DEST_API);
execFileSync('pnpm', ['exec', 'tsc', '--project', 'tsconfig.api-dts.json'], {
  cwd: CLI_ROOT,
  stdio: 'inherit',
});
if (!fs.existsSync(EMITTED_API)) {
  throw new Error(`Expected emitted declarations at ${EMITTED_API} — tsc produced nothing.`);
}
copyDts(EMITTED_API, DEST_API);
fs.rmSync(TMP, {recursive: true, force: true});
console.log('Synced ./api declarations from the JSDoc source of truth.');
