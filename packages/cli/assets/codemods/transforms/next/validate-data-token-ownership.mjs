/**
 * @file Report data-token consumers that need an ownership migration.
 *
 * @input Consumer JavaScript/TypeScript source and generated theme CSS
 * @output No rewritten source; actionable upgrade errors for fallback-less
 *   `var(--color-data-*)` uses (in JS strings, embedded or whole, and in CSS)
 *   and stale generated root-default artifacts
 * @position Next-release upgrade validation for spec:AST-066
 */

import * as path from 'node:path';

export const meta = {
  title: 'Validate data-token ownership',
  description:
    'Reports fallback-less data-token var() uses in source strings and stylesheets for manual CSS/non-CSS migration, and stale generated theme CSS that still owns root defaults.',
  fileExtensions: ['.tsx', '.ts', '.jsx', '.js', '.mjs', '.cjs', '.css'],
};

// A use without a fallback; `var(--color-data-x, <fallback>)` stays valid.
const DIRECT_DATA_VAR = /var\(\s*(--color-data-[a-z0-9-]+)\s*\)/u;
const CSS_COMMENT = /\/\*[\s\S]*?\*\//gu;
const GENERATED_THEME_HEADER = '@generated by `astryx theme build`';
const ROOT_DATA_DECLARATION = /:root\s*\{[^}]*--color-data-/su;

/** @param {any} node */
function staticString(node) {
  if (
    (node?.type === 'StringLiteral' || node?.type === 'Literal') &&
    typeof node.value === 'string'
  ) {
    return node.value;
  }
  if (node?.type === 'TemplateLiteral') {
    // Each static chunk of the template; a use can sit between expressions.
    return (node.quasis ?? [])
      .map((/** @type {any} */ q) => q?.value?.cooked ?? q?.value?.raw ?? '')
      .join('\u0000');
  }
  return undefined;
}

/**
 * @param {import('../../../../authoring/codemod/type').AstryxCodemodFile} file
 * @param {import('../../../../authoring/codemod/type').CodemodTransformApi} api
 * @returns {undefined}
 */
export default function validateDataTokenOwnership(file, api) {
  if (!file.source.includes('--color-data-')) return undefined;

  if (path.extname(file.path) === '.css') {
    if (
      file.source.includes(GENERATED_THEME_HEADER) &&
      ROOT_DATA_DECLARATION.test(file.source)
    ) {
      throw new Error(
        'This generated theme CSS still emits canonical data defaults at :root. Rebuild it with `astryx theme build`; defaults now come from compiled dataVars consumers.',
      );
    }
    const uncommented = file.source.replace(CSS_COMMENT, comment =>
      comment.replace(/[^\n]/gu, ' '),
    );
    const cssMatch = DIRECT_DATA_VAR.exec(uncommented);
    if (cssMatch) {
      const line = uncommented.slice(0, cssMatch.index).split('\n').length;
      throw new Error(
        `Raw var(${cssMatch[1]}) without a fallback at line ${line} needs manual migration: compiled dataVars output is not guaranteed in this stylesheet, so add an explicit fallback or style the element from code that imports dataVars from @astryxdesign/core/theme/dataTokens.stylex.`,
      );
    }
    return undefined;
  }

  const j = api.jscodeshift;
  const root = j(file.source);
  /** @type {{token: string, line: number|null}|null} */
  let found = null;
  const inspect = (/** @type {any} */ node) => {
    if (found) return;
    const value = staticString(node);
    const match =
      typeof value === 'string' ? value.match(DIRECT_DATA_VAR) : null;
    if (match) {
      found = {token: match[1], line: node.loc?.start?.line ?? null};
    }
  };

  /** @param {any} nodePath */
  const inspectPath = nodePath => inspect(nodePath.node);
  root.find(j.StringLiteral).forEach(inspectPath);
  root.find(j.Literal).forEach(inspectPath);
  root.find(j.TemplateLiteral).forEach(inspectPath);

  if (found) {
    const {token, line} = found;
    throw new Error(
      `Direct var(${token})${line == null ? '' : ` at line ${line}`} needs manual migration: CSS-capable code imports dataVars from @astryxdesign/core/theme/dataTokens.stylex; Canvas and other non-CSS APIs use resolveThemeToken() or useTheme().token().`,
    );
  }
  return undefined;
}
