const GENERATED_HEADER_BYTES = 4096;
const GENERATED_COMMENT_MARKER =
  /^\s*(?:\/\/|\/\*+|\*|<!--)\s*(?:@generated\b|(?:this file is )?auto-generated\b[^\n]*\bdo not edit\b|generated file\b[^\n]*\bdo not edit\b|(?:code )?generated by\b[^\n]*\bdo not edit\b)/im;

/**
 * Return the initial whitespace/comment preamble, stopping at the first byte of
 * authored code. This keeps later comments from classifying ordinary source as
 * generated.
 *
 * @param {string} source
 */
function leadingCommentPreamble(source) {
  const header = source.slice(0, GENERATED_HEADER_BYTES);
  let cursor = header.charCodeAt(0) === 0xfeff ? 1 : 0;

  while (cursor < header.length) {
    while (/\s/.test(header[cursor] ?? '')) cursor++;

    if (header.startsWith('#!', cursor) || header.startsWith('//', cursor)) {
      const newline = header.indexOf('\n', cursor);
      cursor = newline === -1 ? header.length : newline + 1;
      continue;
    }

    if (header.startsWith('/*', cursor)) {
      const end = header.indexOf('*/', cursor + 2);
      cursor = end === -1 ? header.length : end + 2;
      continue;
    }

    if (header.startsWith('<!--', cursor)) {
      const end = header.indexOf('-->', cursor + 4);
      cursor = end === -1 ? header.length : end + 3;
      continue;
    }

    break;
  }

  return header.slice(0, cursor);
}

/** @param {string} source */
export function hasGeneratedFileHeader(source) {
  return GENERATED_COMMENT_MARKER.test(leadingCommentPreamble(source));
}

export const GENERATED_FILE_BLOCK_REASON =
  'generated file would have been modified by a codemod; regenerate it with its owning generator instead';
