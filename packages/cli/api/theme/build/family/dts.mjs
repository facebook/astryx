/** @file One declaration module for every complete family member export. */

/**
 * @param {{order: Array<{name: string}>}} graph
 * @param {Map<string, string>} bindings
 * @param {string[]} augmentations
 */
export function generateFamilyTypes(graph, bindings, augmentations) {
  const uniqueAugmentations = [...new Set(augmentations.filter(Boolean))];
  const declarations = graph.order.map(
    node => `export declare const ${bindings.get(node.name)}: DefinedTheme;`,
  );
  return `/** @generated by \`astryx theme build --family\` — do not edit. */\n\nimport type {DefinedTheme} from '@astryxdesign/core/theme';\n\n${declarations.join('\n')}\n${uniqueAugmentations.length > 0 ? `\n${uniqueAugmentations.join('\n\n')}\n` : ''}`;
}
