/**
 * @file esm.mjs
 * @input Complete normalized members and allocated export/registry bindings
 * @output One CSS-free standard ESM family module
 * @position AST-034 FR2/FR7/FR8/FR11 JavaScript artifact generator
 */

import {build as bundle} from 'esbuild';

const SERIALIZED_FIELDS = [
  'tokens',
  'localTokens',
  '__inputTokens',
  '__localTokenOwners',
  '__localTokenLineage',
  'components',
  '__onDark',
  '__onLight',
  '__adaptations',
  '__axes',
];

/** @param {unknown} value */
function indentJson(value) {
  return JSON.stringify(value, null, 2)
    .split('\n')
    .map((line, index) => (index === 0 ? line : `  ${line}`))
    .join('\n');
}

/**
 * @param {{order: Array<{name: string, theme: Record<string, any>}>}} graph
 * @param {Map<string, string>} bindings
 * @param {{imports: string[], expressions: Map<string, {icons?: string, indicators?: string}>, external?: string[], needsPickHelper?: boolean}} [registryPlan]
 */
export async function generateFamilyESM(graph, bindings, registryPlan) {
  const blocks = [
    '/** @generated by `astryx theme build --family` — do not edit. */',
    ...(registryPlan?.imports ?? []),
  ];
  if (registryPlan?.needsPickHelper) {
    blocks.push(`function __astryxPickTheme(namespace, name) {
  const candidates = [namespace.default, ...Object.values(namespace)];
  const theme = candidates.find(value => value && typeof value === 'object' && value.name === name && value.tokens && typeof value.tokens === 'object');
  if (!theme) throw new Error(\`Theme "\${name}" was not found in its bundled source module.\`);
  return theme;
}`);
  }

  for (const node of graph.order) {
    const fields = [
      `  name: ${JSON.stringify(node.name)},`,
      '  __built: true,',
    ];
    for (const field of SERIALIZED_FIELDS) {
      const value = node.theme[field];
      if (value === undefined) continue;
      fields.push(`  ${field}: ${indentJson(value)},`);
    }
    const registry = registryPlan?.expressions.get(node.name);
    if (registry?.icons) fields.push(`  icons: ${registry.icons},`);
    if (registry?.indicators) {
      fields.push(`  indicators: ${registry.indicators},`);
    }
    blocks.push(
      `export const ${bindings.get(node.name)} = {\n${fields.join('\n')}\n};`,
    );
  }

  const source = `${blocks.join('\n\n')}\n`;
  if ((registryPlan?.imports.length ?? 0) === 0) return source;

  const result = await bundle({
    stdin: {
      contents: source,
      loader: 'js',
      resolveDir: process.cwd(),
      sourcefile: 'astryx-theme-family-entry.mjs',
    },
    bundle: true,
    write: false,
    outfile: 'family.js',
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    packages: 'external',
    external: registryPlan?.external ?? [],
    legalComments: 'none',
    minifyWhitespace: true,
    minifyIdentifiers: false,
    minifySyntax: false,
    banner: {
      js: '/** @generated by `astryx theme build --family` — do not edit. */',
    },
    logLevel: 'silent',
    charset: 'utf8',
  });
  const cssOutput = result.outputFiles.find(file => file.path.endsWith('.css'));
  if (cssOutput) {
    throw new Error(
      'A theme registry source imported CSS; the required family ESM must stay CSS-free.',
    );
  }
  const jsOutput = result.outputFiles.find(file => file.path.endsWith('.js'));
  if (!jsOutput || result.outputFiles.length !== 1) {
    throw new Error(
      'Family registry bundling did not produce exactly one ESM file.',
    );
  }
  return jsOutput.text.endsWith('\n') ? jsOutput.text : `${jsOutput.text}\n`;
}
