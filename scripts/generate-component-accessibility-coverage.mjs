import fs from 'node:fs';
import path from 'node:path';
import {inspect} from 'node:util';
import {fileURLToPath} from 'node:url';
import {
  buildRegisteredAccessibilityCoverage,
  generatedCoverageUrl,
} from './accessibility/component-audit-registry.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = fileURLToPath(generatedCoverageUrl);

function generatedSource() {
  const coverage = buildRegisteredAccessibilityCoverage();
  const exports = Object.entries(coverage)
    .map(
      ([exportName, componentCoverage]) =>
        `/** @type {import('@astryxdesign/cli/authoring').ComponentAccessibilityThemeCoverage[]} */\nexport const ${exportName} = ${inspect(componentCoverage, {
          breakLength: 100,
          compact: true,
          depth: null,
        })};`,
    )
    .join('\n\n');
  return `// Copyright (c) Meta Platforms, Inc. and affiliates.\n\n// Generated by scripts/generate-component-accessibility-coverage.mjs.\n\n${exports}\n`;
}

const next = generatedSource();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== next) {
    console.error(
      'Component accessibility coverage is stale. Run: pnpm exec tsx scripts/generate-component-accessibility-coverage.mjs',
    );
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(OUTPUT, next);
  console.log(`Generated ${path.relative(ROOT, OUTPUT)}`);
}
