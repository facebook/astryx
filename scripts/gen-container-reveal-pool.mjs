/**
 * @file gen-container-reveal-pool.mjs
 * @input POOL_SIZE
 * @output packages/core/src/hooks/containerReveal.pool.stylex.ts
 * @position Generator for the useContainerReveal marker pool. `stylex.create`
 *   must be static (no runtime loops), and each marker's reveal styles must be
 *   compiled against that specific marker, so the N repeated blocks are
 *   generated rather than hand-written.
 *
 * Run: node scripts/gen-container-reveal-pool.mjs
 */

import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, join} from 'node:path';

const POOL_SIZE = 8;
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '../packages/core/src/hooks/containerReveal.pool.stylex.ts',
);

const transition = `transitionProperty: 'opacity',
    transitionDuration: {
      default: durationVars['--duration-fast'],
      '@media (prefers-reduced-motion: reduce)': '0s',
    },
    transitionTimingFunction: easeVars['--ease-standard'],`;

function toggled(m, hidden, shown) {
  return `{
      default: ${hidden},
      [stylex.when.ancestor(':hover', ${m})]: {'@media (hover: hover)': ${shown}},
      [stylex.when.ancestor(':focus-within', ${m})]: ${shown},
      '@media (any-pointer: coarse)': ${shown},
    }`;
}

function block(i) {
  const m = `m${i}`;
  return `
export const ${m} = stylex.defineMarker();
const s${i} = stylex.create({
  reveal: {
    ${transition}
    opacity: ${toggled(m, '0', '1')},
    position: ${toggled(m, "'absolute'", "'static'")},
    width: ${toggled(m, "'1px'", "'auto'")},
    height: ${toggled(m, "'1px'", "'auto'")},
    margin: ${toggled(m, "'-1px'", "'0'")},
    overflow: ${toggled(m, "'hidden'", "'visible'")},
    clip: ${toggled(m, "'rect(0, 0, 0, 0)'", "'auto'")},
    whiteSpace: ${toggled(m, "'nowrap'", "'normal'")},
  },
  revealLayoutPreserved: {
    ${transition}
    opacity: ${toggled(m, '0', '1')},
    pointerEvents: ${toggled(m, "'none'", "'auto'")},
  },
  conceal: {
    ${transition}
    opacity: {
      default: 1,
      [stylex.when.ancestor(':hover', ${m})]: {'@media (hover: hover)': 0},
    },
  },
  concealLayoutPreserved: {
    ${transition}
    opacity: {
      default: 1,
      [stylex.when.ancestor(':hover', ${m})]: {'@media (hover: hover)': 0},
    },
  },
});`;
}

const header = `// Copyright (c) Meta Platforms, Inc. and affiliates.

/**
 * @file containerReveal.pool.stylex.ts
 * @input Uses StyleX, theme tokens
 * @output A fixed pool of scoped markers, each paired with its reveal style
 *   blocks (reveal / conceal, each with a layout-preserved variant) compiled
 *   against that marker.
 * @position Internal to useContainerReveal. GENERATED by
 *   scripts/gen-container-reveal-pool.mjs — do not edit by hand.
 *
 * WHY A POOL: \`stylex.when.ancestor(':hover', marker)\` welds the marker's
 * class into the compiled selector (\`.marker:hover *\`), so a marker and the
 * styles referencing it are inseparable at compile time. A single shared
 * marker would leak hover/focus across NESTED reveal containers (an ancestor
 * container's \`:hover\` matches a descendant container's revealed content).
 * Pre-declaring N markers lets useContainerReveal hand each concurrently
 * mounted container a distinct marker (free-list in useContainerReveal),
 * isolating nested containers without the caller authoring any StyleX.
 *
 * SYNC: When the block shape changes, edit
 * scripts/gen-container-reveal-pool.mjs and useContainerReveal.ts, then
 * regenerate (node scripts/gen-container-reveal-pool.mjs) and commit.
 */

import * as stylex from '@stylexjs/stylex';
import {durationVars, easeVars} from '../theme/tokens.stylex';

export const POOL_SIZE = ${POOL_SIZE};
`;

const blocks = Array.from({length: POOL_SIZE}, (_, i) => block(i)).join('\n');

const footer = `

// The compiled StyleX style objects carry \`when.ancestor\` conditionals that
// the public \`StyleXStyles\` type does not model, so the slot shape is inferred
// from the generated blocks rather than annotated.
export const POOL = [
${Array.from(
  {length: POOL_SIZE},
  (_, i) =>
    `  {marker: m${i}, reveal: s${i}.reveal, revealLayoutPreserved: s${i}.revealLayoutPreserved, conceal: s${i}.conceal, concealLayoutPreserved: s${i}.concealLayoutPreserved},`,
).join('\n')}
] as const;

export type RevealSlot = (typeof POOL)[number];
`;

writeFileSync(OUT, header + '\n' + blocks + footer);
console.log(`Wrote ${OUT}`);
